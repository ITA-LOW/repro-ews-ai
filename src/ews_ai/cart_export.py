"""Train the on-device CART on unscaled physical features and emit C.

The tree is the Table 2 CART (same depth / min-leaf / seed / temporal split)
without StandardScaler, so MCU thresholds stay in °C, mm, and percent.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
from sklearn.tree import DecisionTreeClassifier

from ews_ai.models import (
    count_sklearn_params,
    hazard_metrics,
    map_perception_label,
    temporal_per_station_indices,
)
from ews_ai.paths import REPO_ROOT

FEATURE_ORDER = (
    "temperature_c",
    "humidity_pct",
    "precip_6h",
    "precip_24h",
    "soil_moisture",
)

DEFAULT_HEADER = REPO_ROOT / "firmware" / "src" / "cart_model.h"


def fit_unscaled_cart(
    x: np.ndarray,
    y: np.ndarray,
    station_ids: np.ndarray,
    cfg: dict[str, Any],
) -> tuple[DecisionTreeClassifier, dict[str, Any]]:
    """Fit CART on the temporal train split; evaluate on the temporal test split."""
    seed = int(cfg.get("seed", 42))
    cls_cfg = cfg.get("classification") or {}
    test_fraction = float(cfg["split"]["test_fraction"])
    train_idx, test_idx = temporal_per_station_indices(station_ids, test_fraction)

    tree = DecisionTreeClassifier(
        max_depth=int(cls_cfg.get("cart_max_depth", 10)),
        min_samples_leaf=int(cls_cfg.get("cart_min_samples_leaf", 50)),
        random_state=seed,
    )
    tree.fit(x[train_idx], y[train_idx])
    pred = np.asarray(tree.predict(x[test_idx]), dtype=np.int32)
    metrics = hazard_metrics(y[test_idx], pred)
    metrics["n_nodes"] = int(tree.tree_.node_count)
    metrics["n_leaves"] = int(tree.tree_.n_leaves)
    metrics["max_depth"] = int(tree.get_depth())
    metrics["n_params"] = count_sklearn_params("cart", tree)
    metrics["n_train"] = int(len(train_idx))
    metrics["n_test"] = int(len(test_idx))
    return tree, metrics


def predict_cart(tree: DecisionTreeClassifier, x: np.ndarray) -> np.ndarray:
    return np.asarray(tree.predict(x), dtype=np.int32)


def render_c_header(
    tree: DecisionTreeClassifier,
    features: tuple[str, ...] = FEATURE_ORDER,
) -> str:
    t = tree.tree_
    n = int(t.node_count)
    left = t.children_left
    right = t.children_right
    feat = t.feature
    thr = t.threshold
    values = t.value  # (n_nodes, 1, n_classes)

    lines = [
        "/* SPDX-License-Identifier: MIT */",
        "/* Auto-generated by experiments/06_export_cart.py — do not edit. */",
        "/* Unscaled CART. Feature order matches configs/experiment.yaml. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define CART_N_FEATURES {len(features)}",
        f"#define CART_N_NODES {n}",
        f"#define CART_N_CLASSES {int(values.shape[-1])}",
        "",
    ]
    for i, name in enumerate(features):
        lines.append(f"#define CART_F_{name.upper()} {i}")
    lines += [
        "",
        "typedef struct {",
        "    float threshold;",
        "    int16_t left;",
        "    int16_t right;",
        "    int8_t feature; /* -1 = leaf */",
        "    int8_t klass;",
        "} CartNode;",
        "",
        f"/* sizeof(CartNode) is typically 12. Flash ~= {n} * 12 bytes. */",
        "static const CartNode CART_NODES[CART_N_NODES] = {",
    ]
    for i in range(n):
        is_leaf = int(left[i]) < 0
        klass = int(np.argmax(values[i, 0])) if is_leaf else 0
        feature = -1 if is_leaf else int(feat[i])
        threshold = 0.0 if is_leaf else float(thr[i])
        lft = -1 if is_leaf else int(left[i])
        rgt = -1 if is_leaf else int(right[i])
        comment = "leaf" if is_leaf else features[feature]
        lines.append(
            f"    {{{threshold:.6f}f, {lft}, {rgt}, {feature}, {klass}}}, "
            f"/* {i} {comment} */"
        )
    lines += [
        "};",
        "",
        "/* sklearn rule: feature <= threshold → left. */",
        "static inline int cart_predict(const float x[CART_N_FEATURES]) {",
        "    int i = 0;",
        "    while (CART_NODES[i].feature >= 0) {",
        "        if (x[CART_NODES[i].feature] <= CART_NODES[i].threshold) {",
        "            i = CART_NODES[i].left;",
        "        } else {",
        "            i = CART_NODES[i].right;",
        "        }",
        "    }",
        "    return (int)CART_NODES[i].klass;",
        "}",
        "",
        "static inline int cart_is_hazard(int klass) { return klass != 0; }",
        "",
    ]
    return "\n".join(lines) + "\n"


def write_header(tree: DecisionTreeClassifier, path: Path | None = None) -> Path:
    dest = path or DEFAULT_HEADER
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(render_c_header(tree), encoding="utf-8")
    return dest


def load_xy(df, features: tuple[str, ...] = FEATURE_ORDER):
    x = df[list(features)].to_numpy(dtype=np.float64)
    y = map_perception_label(df["risk_label"].to_numpy())
    stations = df["station_id"].to_numpy()
    return x, y, stations
